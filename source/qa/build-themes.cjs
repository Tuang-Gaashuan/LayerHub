'use strict';
// Generate scoped overrides from CSS syntax trees, preserving media/supports rules.
const fs=require('node:fs'),path=require('node:path'),css=require('./frontend-deps/node_modules/css-tree');
const web=path.resolve(__dirname,'../web');
const blend=(rgb,base,t)=>'#'+rgb.map((v,i)=>Math.round(v*t+base[i]*(1-t)).toString(16).padStart(2,'0')).join('');
const parseHex=h=>{h=h.slice(1);if(h.length===3)h=[...h].map(c=>c+c).join('');return h.length===6?[0,2,4].map(i=>parseInt(h.slice(i,i+2),16)):null};
function colour(h,property,accent){
 const rgb=parseHex(h);if(!rgb)return h;const [r,g,b]=rgb,spread=Math.max(...rgb)-Math.min(...rgb),avg=(r+g+b)/3;
 if(accent)return /^(?:#3159ed|#264ad3|#2955ed|#3159d8|#3159ef)$/i.test(h)?'var(--blue)':h;
 if(property.startsWith('background')){if(avg>205)return spread<34?'var(--ui-surface-soft)':blend(rgb,[24,34,49],.13);if(h==='#fff'||h==='#ffffff')return 'var(--surface)';return h}
 if(property.startsWith('border')||property==='box-shadow')return avg>175?(spread<65?'var(--line)':blend(rgb,[24,34,49],.28)):h;
 if(property==='color'){if(avg>240&&spread<15)return h;if(spread<95)return avg<110?'var(--ink)':'var(--ui-muted)';return blend(rgb,[255,255,255],.58)}
 return h;
}
const outputs=[];
for(const file of fs.readdirSync(web).filter(f=>f.endsWith('.css')&&!['themes.css','themes.generated.css','appearance.css','source-offer.css'].includes(f))){
 const tree=css.parse(fs.readFileSync(path.join(web,file),'utf8')),parents=[];
 css.walk(tree,{enter(node){
  if(node.type==='Atrule')parents.push(node);
  if(node.type!=='Rule'||node.prelude?.type!=='SelectorList')return;
  const original=css.generate(node.prelude);
  if(/(?:color-dot|swatch|filament-colou?r|spool-colou?r|spool-thread|printer-illustration)/i.test(original))return;
  for(const accent of [false,true]){
   if(accent&&/(?:badge|status|state-|alert|warning|error|live-|avatar|notification)/i.test(original))continue;
   const declarations=[];
   node.block.children.forEach(d=>{
    if(d.type!=='Declaration'||!['color','background','background-color','border','border-color','border-top','border-bottom','border-left','border-right','outline-color'].includes(d.property))return;
    const before=css.generate(d.value);
    if(/var\(--(?:ui-muted|ink|line|blue)\b/.test(before))return;
    let after=before.replace(/#[\da-f]{3,8}\b/gi,h=>{if(!accent&&d.property.startsWith('background')&&/^#(?:fff|ffffff)$/i.test(h))return 'var(--surface)';return colour(h.toLowerCase(),d.property,accent)});
    if(accent&&d.property.startsWith('background'))after=after.replaceAll('var(--blue)',original.includes(':hover')?'var(--accent-hover)':'var(--accent-button)');
    if(!accent){if(d.property.startsWith('background'))after=after.replace(/\bwhite\b/g,'var(--surface)').replace(/#ffffff[\da-f]{2}/gi,'var(--surface)');else if(d.property.startsWith('border'))after=after.replace(/\bwhite\b/g,'var(--line)')}
    if(after!==before)declarations.push(d.property+':'+after+(d.important?'!important':'')+';');
   });
   if(!declarations.length)continue;
   const prefix=accent?'html[data-ui-accent]':'html[data-ui-color-scheme="dark"]',selectors=[];
   node.prelude.children.forEach(sel=>{let v=css.generate(sel);if(/^(:root|html)(?=[\s[.#:>+~]|$)/.test(v))v=v.replace(/^(:root|html)/,prefix);else v=prefix+' '+v;selectors.push(v)});
   let rule=selectors.join(',')+'{'+declarations.join('')+'}';
   for(const a of [...parents].reverse())if(['media','supports','container'].includes(a.name))rule='@'+a.name+' '+css.generate(a.prelude)+'{'+rule+'}';
   outputs.push(rule);
  }
 },leave(node){if(node.type==='Atrule')parents.pop()}});
}
const content='/* Generated by qa/build-themes.cjs. Edit source CSS or the generator. */\n'+outputs.join('\n')+'\n';
css.parse(content);
const target=path.join(web,'themes.generated.css');if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==content)throw Error('Generated themes are stale')}else fs.writeFileSync(target,content);
console.log(JSON.stringify({themeOverrides:outputs.length}));
